cat("== fission workflow code (rnaseqGene 'Time course experiments') ==\n")
os_acceptance_lib(suite)
library("fission")
data("fission")
print(levels(fission$strain)); print(levels(fission$minute)); print(dim(fission))
ddsTC <- DESeqDataSet(fission, ~ strain + minute + strain:minute)
ddsTC <- DESeq(ddsTC, test="LRT", reduced = ~ strain + minute)
resTC <- results(ddsTC)
resTC$symbol <- mcols(ddsTC)$symbol
print(head(resTC[order(resTC$padj),], 4))
o <- head(resTC[order(resTC$padj),], 4)
print(format(as.data.frame(o[, 1:6]), digits = 12))
rn <- resultsNames(ddsTC); cat("last coef:", rn[length(rn)], "\n")
r2 <- results(ddsTC, name = rn[length(rn)])
cat("results(name = last coef) identical to results():", identical(as.data.frame(r2), as.data.frame(resTC[, 1:6])),
    isTRUE(all.equal(as.data.frame(r2), as.data.frame(resTC[, 1:6]), tolerance = 0)), "\n")
print(mcols(r2)$description); print(mcols(resTC)$description)
r3 <- results(ddsTC, name = "strainmut.minute30")
cat("P identical when name changes:", identical(r3$pvalue, resTC$pvalue), " padj identical:", identical(r3$padj, resTC$padj),
    " LFC differs:", !identical(r3$log2FoldChange, resTC$log2FoldChange), "\n")
cat("== fission with reference mut (engine radix order) ==\n")
f2 <- fission
f2$strain <- factor(as.character(f2$strain), levels = c("mut", "wt"))
dd2 <- DESeqDataSet(f2, ~ strain + minute + strain:minute)
dd2 <- DESeq(dd2, test="LRT", reduced = ~ strain + minute)
rr <- results(dd2)
ii <- match(rownames(o), rownames(rr))
print(format(as.data.frame(rr[ii, ]), digits = 12))
cat("max rel P diff (all):", max(abs(rr$pvalue - resTC$pvalue) / pmax(resTC$pvalue, 1e-300), na.rm = TRUE),
    " NA same:", identical(is.na(rr$pvalue), is.na(resTC$pvalue)), identical(is.na(rr$padj), is.na(resTC$padj)), "\n")
cat("max abs LFC(mut ref) + LFC(wt ref):", max(abs(rr$log2FoldChange + resTC$log2FoldChange), na.rm = TRUE), "\n")
