# S4 probe 2: why num.sv(method = "leek") differs (vignette 2 vs in-memory). ASCII only.
suite <- normalizePath(".")
source(file.path(suite, "skills", "_shared", "scripts", "module_kit.R"))
source(file.path(suite, "skills", "sva-batch", "tests", "fixtures", "make_bladderbatch.R"))
bladderEset <- os_acceptance_data(suite, "bladderbatch", "bladderdata")
suppressMessages({ library(sva); library(limma); library(Biobase) })
cat("==== num.sv ====\n"); writeLines(deparse(sva::num.sv))
cat("==== ComBat_seq head ====\n"); writeLines(head(deparse(sva::ComBat_seq), 120))
cat("rowVars from:", environmentName(environment(get("rowVars", envir = asNamespace("sva")))), "\n")
print(sessionInfo())
cat("La_library:", La_library(), " BLAS:", extSoftVersion()["BLAS"], "\n")
pheno = pData(bladderEset); edata = exprs(bladderEset)
mod = model.matrix(~as.factor(cancer), data=pheno)
cat("storage:", storage.mode(edata), dim(edata), "\n")
cat("leek in-memory:", num.sv(edata, mod, method = "leek"), "\n")
tmp <- tempfile(); bb <- make_bladderbatch(tmp, suite)
m2 <- os_read_matrix(bb$exprs, "x")
cat("identical rownames order:", identical(rownames(m2), rownames(edata)), " colnames:", identical(colnames(m2), colnames(edata)), "\n")
m2 <- m2[rownames(edata), colnames(edata)]
cat("max abs diff after TSV round trip:", max(abs(m2 - edata)), "\n")
cat("leek TSV (reordered to vignette order):", num.sv(m2, mod, method = "leek"), "\n")
m3 <- os_read_matrix(bb$exprs, "x")
cat("leek TSV engine order:", num.sv(m3, mod, method = "leek"), "\n")
cat("leek in-memory rows sorted:", num.sv(edata[sort(rownames(edata), method = "radix"), ], mod, method = "leek"), "\n")
set.seed(1); for (k in 1:5) { e <- edata + matrix(rnorm(length(edata), sd = 1e-12), nrow(edata)); cat("leek perturbed 1e-12 #", k, ":", num.sv(e, mod, method = "leek"), "\n") }
# inside leek: eigen-based statistic
H <- mod %*% solve(t(mod) %*% mod) %*% t(mod)
res <- edata - t(H %*% t(edata))
uu <- eigen(t(res) %*% res)
print(signif(uu$values[1:12], 12))
