# S4 probe (limma-voom F1/F3): RNAseq123 workflow replay on the sha-locked
# GSE63310_RAW.tar and inspection of the locked voom / voomLmFit / plotMDS
# formals and outputs. Run from the suite root inside omicstat-r:2026.09.1.
suppressPackageStartupMessages({ library(limma); library(edgeR) })
cat("limma", as.character(packageVersion("limma")), "edgeR", as.character(packageVersion("edgeR")), "\n")
show_formals <- function(label, f) cat(label, ":", paste(names(formals(f)), vapply(formals(f), function(z) paste(deparse(z), collapse = ""), ""), sep = "=", collapse = ", "), "\n")
show_formals("voom", limma::voom)
show_formals("voomWithQualityWeights", limma::voomWithQualityWeights)
show_formals("voomLmFit", edgeR::voomLmFit)
show_formals("plotMDS", limma::plotMDS)
show_formals("plotMDS.default", limma:::plotMDS.default)
show_formals("plotMDS.DGEList", edgeR:::plotMDS.DGEList)
show_formals("filterByExpr.default", edgeR:::filterByExpr.default)
show_formals("filterByExpr.DGEList", edgeR:::filterByExpr.DGEList)
tarfile <- "acceptance/data/GSE63310_RAW.tar"
cat("sha256", digest::digest(file = tarfile, algo = "sha256"), "\n")
print(utils::untar(tarfile, list = TRUE))
wd <- file.path(tempdir(), "rnaseq123"); dir.create(wd)
utils::untar(tarfile, exdir = wd)
old <- setwd(wd)
# limmaWorkflow.Rmd (RELEASE_3_23 @09a5145) lines 83-116, 193-195, 238-239, 310-326, 348-352, 367-395
files <- c("GSM1545535_10_6_5_11.txt", "GSM1545536_9_6_5_11.txt",
           "GSM1545538_purep53.txt", "GSM1545539_JMS8-2.txt",
           "GSM1545540_JMS8-3.txt", "GSM1545541_JMS8-4.txt",
           "GSM1545542_JMS8-5.txt", "GSM1545544_JMS9-P7c.txt",
           "GSM1545545_JMS9-P8c.txt")
cat("R.utils installed:", requireNamespace("R.utils", quietly = TRUE), "
")
x <- readDGE(paste0(files, ".gz"), columns = c(1, 3))
colnames(x) <- sub("[.]txt$", "", colnames(x)); print(colnames(x))
print(dim(x))
samplenames <- substring(colnames(x), 12, nchar(colnames(x)))
colnames(x) <- samplenames
group <- as.factor(c("LP", "ML", "Basal", "Basal", "ML", "LP", "Basal", "ML", "LP"))
x$samples$group <- group
lane <- as.factor(rep(c("L004", "L006", "L008"), c(3, 4, 2)))
x$samples$lane <- lane
print(x$samples)
print(table(rowSums(x$counts == 0) == 9))
x_full <- x
keep.exprs <- filterByExpr(x, group = group)
x <- x[keep.exprs, , keep.lib.sizes = FALSE]
print(dim(x))
x <- calcNormFactors(x, method = "TMM")
print(x$samples$norm.factors)
design <- model.matrix(~0 + group + lane)
colnames(design) <- gsub("group", "", colnames(design))
contr.matrix <- makeContrasts(BasalvsLP = Basal - LP, BasalvsML = Basal - ML, LPvsML = LP - ML, levels = colnames(design))
t0 <- Sys.time()
v <- voom(x, design, plot = FALSE)
print(v$span); print(round(v$E[1:5, ], 3)); print(round(v$weights[1:5, ], 2))
vfit <- lmFit(v, design)
vfit <- contrasts.fit(vfit, contrasts = contr.matrix)
efit <- eBayes(vfit)
print(summary(decideTests(efit)))
tfit <- treat(vfit, lfc = 1)
dt <- decideTests(tfit)
print(summary(dt))
de.common <- which(dt[, 1] != 0 & dt[, 2] != 0)
print(length(de.common))
basal.vs.lp <- topTreat(tfit, coef = 1, n = Inf)
basal.vs.ml <- topTreat(tfit, coef = 2, n = Inf)
print(head(basal.vs.lp)); print(head(basal.vs.ml))
cat("workflow time", format(Sys.time() - t0), "\n")
# filterByExpr with the design (suite D-V2) vs group (workflow)
kd <- filterByExpr(x_full, design = design)
cat("filterByExpr design keeps", sum(kd), "; group keeps", sum(keep.exprs), "; overlap", sum(kd & keep.exprs), "\n")
h <- hat(design); cat("max hat", max(h), "MinSampleSize(design)", 1 / max(h), "\n")
# the same fit on the suite's parameterisation ~ lane + group (ref LP)
st <- data.frame(group = relevel(group, "LP"), lane = lane)
# factor order as os_limma_design: levels = c(reference, target, others)
st$group <- factor(as.character(group), levels = c("LP", "Basal", "ML"))
mm <- model.matrix(~ lane + group, data = st)
v2 <- voom(x, mm, plot = FALSE)
cat("voom E identical across parameterisations:", isTRUE(all.equal(v$E, v2$E)), isTRUE(all.equal(v$weights, v2$weights)), "\n")
f2 <- eBayes(lmFit(v2, mm))
tt2 <- topTable(f2, coef = "groupBasal", number = Inf, sort.by = "none")
tt1 <- topTable(efit, coef = "BasalvsLP", number = Inf, sort.by = "none")
cat("max |dP| coef vs contrast", max(abs(tt1$P.Value - tt2$P.Value)), "max |dt|", max(abs(tt1$t - tt2$t)), "\n")
# save.plot outputs
vs <- voom(x, design, plot = FALSE, save.plot = TRUE)
cat("voom save.plot names:", names(vs), "\n"); str(vs$voom.line)
vl <- voomLmFit(x, design, plot = FALSE, save.plot = TRUE, keep.EList = TRUE)
cat("voomLmFit names:", names(vl), "\n"); cat("voomLmFit span", format(vl$span), "\n")
vq <- voomWithQualityWeights(x, design, plot = FALSE)
cat("vwqw names:", names(vq), "; span", format(vq$span), "\n")
vlw <- voomLmFit(x, design, sample.weights = TRUE, plot = FALSE, save.plot = TRUE, keep.EList = TRUE)
cat("voomLmFit sw names:", names(vlw), "\n"); print(vlw$targets)
md <- plotMDS(x, plot = FALSE)
cat("plotMDS names:", names(md), "\n"); print(md$var.explained[1:3]); print(md$top); print(md$gene.selection)
setwd(old)
