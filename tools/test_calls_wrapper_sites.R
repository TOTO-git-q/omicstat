# Positive and negative checks: dispatch must not bypass registry assertions.
source("skills/_shared/scripts/calls_check.R")
source("tools/calls_wrapper_sites.R")
p <- tempfile(fileext = ".R")
reg <- list(package_versions = list(stats = "locked"), calls = list(
  list(fn = "stats::prcomp", args = list(center = list(value = TRUE)))), accessors = list())
writeLines("os_bioc_call(stats::prcomp, NULL, x = z, center = TRUE)", p)
stopifnot(check_calls(p, reg)$ok)
writeLines("os_bioc_call(stats::prcomp, NULL, x = z)", p)
stopifnot(any(grepl("^C1", check_calls(p, reg)$problems)))
writeLines("os_bioc_call(stats::kmeans, NULL, x = z, centers = 2)", p)
stopifnot(any(grepl("^C2", check_calls(p, reg)$problems)), any(grepl("^C3", check_calls(p, reg)$problems)))
writeLines("do.call(stats::prcomp, unknown_args)", p)
stopifnot(any(grepl("^C1", check_calls(p, reg)$problems)))
reg$calls[[1]]$args <- list()
stopifnot(check_calls(p, reg)$ok)
writeLines("unrelated(stats::prcomp)", p)
stopifnot(any(grepl("^C3", check_calls(p, reg)$problems)))
unlink(p)
cat("PASS: wrapper dispatch preserves C1/C2/C3 and rejects unproved dynamic arguments\n")
