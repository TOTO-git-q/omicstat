here <- dirname(normalizePath(sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])))
mod <- dirname(here); shared <- file.path(mod,"..","_shared","scripts")
for(f in c("module_kit.R","effect_table.R","dose_scope_support.R","fig_all.R"))source(file.path(shared,f))
source(file.path(mod,"scripts/nlme_dose_core.R"))
check<-function(ok,msg){if(!isTRUE(ok))stop(paste("FAIL",msg));cat("PASS:",msg,"\n")}
refuse<-function(expr,code){msg<-tryCatch({force(expr);"NO_ERROR"},error=conditionMessage);check(grepl(code,msg,fixed=TRUE),paste("typed refusal",code))}
run<-function(){
 set.seed(713);ids<-c('01','1',sprintf('S%02d',3:16));tmp<-tempfile();dir.create(tmp);on.exit(unlink(tmp,recursive=TRUE))
 d<-expand.grid(dose=c(.01,.03,.1,.3,1,3,10,30),subject=ids,stringsAsFactors=FALSE)
 shift<-rnorm(16,0,.5);d$response<-100/(1+exp(-(log(d$dose)-log(1.6)-shift[match(d$subject,ids)])/.7))+rnorm(nrow(d),0,2)
 p<-file.path(tmp,'d.csv');write.csv(d,p,row.names=FALSE)
 a<-list(input=p,`unit-col`='subject',`technical-policy`='reject',response='response',dose='dose',`dose-unit`='ng/mL',direction='increasing',`random-parameter`='logED50',method='ML',residual='independent',`singular-tol`=.0001,`max-iter`=100,`ci-level`=.95,`study-contract-sha256`=paste(rep('0',64),collapse=''))
 x<-nlme_dose_compute(a)
 check(x$metadata$n_subjects==16 && x$tables$effect_table$n_unweighted==16,'biological n is subjects not repeated doses')
 check(all(c('01','1') %in% x$tables$biological_units$subject),'leading-zero subjects remain distinct')
 write.csv(d[rev(seq_len(nrow(d))),],p,row.names=FALSE);y<-nlme_dose_compute(a)
 check(isTRUE(all.equal(x$tables$parameters,y$tables$parameters,tolerance=1e-10)),'row permutation does not change model fit')
 b<-a;b$subject<-'different';refuse(nlme_dose_compute(b),'OS_CONFLICTING_PARAMETERS')
 b<-a;b[['unit-col']]<-NULL;refuse(nlme_dose_compute(b),'OS_MISSING_PARAMETER')
 b<-a;b[['technical-policy']]<-'mean';refuse(nlme_dose_compute(b),'OS_INVALID_PARAMETER')
 write.csv(rbind(d,d[1,]),p,row.names=FALSE);refuse(nlme_dose_compute(a),'OS_INVALID_DESIGN')
 write.csv(d,p,row.names=FALSE);b<-a;b$method<-'REML';y<-nlme_dose_compute(b)
 check(all(is.finite(y$tables$parameters$estimate)),'actual REML model executes')
 dec<-d;dec$response<-100-dec$response;write.csv(dec,p,row.names=FALSE);b<-a;b$direction<-'decreasing';y<-nlme_dose_compute(b)
 check(y$tables$parameters$estimate[y$tables$parameters$term=='scal']<0,'actual decreasing model has declared slope sign')
 # Amplitude random effect is a different supported model, actually fit here.
 amp<-d;amp$response<-(100+rnorm(16,0,12)[match(amp$subject,ids)])/(1+exp(-(log(amp$dose)-log(1.6))/.7))+rnorm(nrow(amp),0,2)
 write.csv(amp,p,row.names=FALSE);b<-a;b[['random-parameter']]<-'Asym';y<-nlme_dose_compute(b)
 check(y$tables$variance_components$component[1]=='Asym' && y$tables$variance_components$variance[1]>0,'actual random-amplitude fit executes')
 # Make one dose observed for just one subject, preserving >=5 doses each.
 uneven<-d[!(d$dose==.01 & d$subject!='01'),];write.csv(uneven,p,row.names=FALSE);y<-nlme_dose_compute(a)
 check(y$tables$response_summary$n_subjects[y$tables$response_summary$dose==.01]==1 && is.na(y$tables$response_summary$sem[y$tables$response_summary$dose==.01]),'one-subject dose has undefined SEM, not zero')
 check(all(vapply(ids,function(id){z<-y$tables$subject_predictions[y$tables$subject_predictions$subject==id,];o<-uneven$dose[uneven$subject==id];min(z$dose)>=min(o)*(1-1e-12)&&max(z$dose)<=max(o)*(1+1e-12)},logical(1))),'subject predictions stay within observed subject ranges')
 out<-file.path(tmp,'figures');dir.create(out)
 os_finalize_figure(os_scope_response(y$tables$response_summary,y$metadata),file.path(out,'unequal_response'),root=out)
 check(file.exists(file.path(out,'unequal_response.png')),'unequal-grid means remain renderable without invented SEM')
 b<-a;b$direction<-'decreasing';refuse(nlme_dose_compute(b),'OS_INVALID_DESIGN')
 check(!file.exists('Rplots.pdf'),'no device leak')
}
run()
