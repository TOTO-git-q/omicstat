d <- lme4::sleepstudy;d$period <- factor(ifelse(d$Days<5,"early","late"),levels=c("early","late"))
fit <- lme4::lmer(Reaction~period+(1|Subject),data=d,REML=TRUE,control=lme4::lmerControl(optimizer="nloptwrap"))
hash <- paste(rep("0",64),collapse="")
fm <- tempfile(fileext=".rds");mm <- tempfile(fileext=".rds");saveRDS(fit,fm)
saveRDS(list(n_obs=nrow(d),n_subject=18L,study_contract_sha256=hash),mm)
