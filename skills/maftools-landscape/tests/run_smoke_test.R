# requires: maftools, jsonlite, digest, ggplot2
.this <- normalizePath(sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1]))
mod <- dirname(dirname(.this)); suite <- dirname(dirname(mod)); shared <- file.path(suite, "skills", "_shared", "scripts")
source(file.path(shared, "module_kit.R")); source(file.path(shared, "handoff.R"))
tmp <- file.path(Sys.getenv("OMICSTAT_TEST_TMP", tempdir()), "maf-smoke"); dir.create(tmp, recursive = TRUE, showWarnings = FALSE)
n <- 0L
check <- function(ok, label) { n <<- n + 1L; cat(if (isTRUE(ok)) "PASS:" else "FAIL:", label, "\n"); if (!isTRUE(ok)) stop(label) }
entry <- file.path(mod, "scripts", "run_maftools_landscape.R")
run <- function(...) { out <- system2("Rscript", c(shQuote(entry), unlist(list(...))), stdout = TRUE, stderr = TRUE); list(status = attr(out, "status") %||% 0, out = out) }
sha <- function(p) digest::digest(file = p, algo = "sha256")
maf <- system.file("extdata", "tcga_laml.maf.gz", package = "maftools"); clin <- system.file("extdata", "tcga_laml_annot.tsv", package = "maftools")
check(sha(maf) == "d102b071a052265b6f8ad7947bad1d58d3e3036fd17d6b274f7ea09a376cd6a0" && sha(clin) == "7033030d52868e9a0f35ffd78f45a9d7a126c2edef90cf9e74e4f5d78990a710", "package anchor file hashes")
base <- c("--call-source", "TCGA-LAML-vignette", "--capture-size", "50")
a0 <- file.path(tmp, "anchor"); z <- run(base, "--input", shQuote(maf), "--clinical", shQuote(clin), "--outdir", shQuote(a0)); check(z$status == 0, paste("end to end", paste(tail(z$out, 3), collapse = " | ")))
s <- utils::read.csv(file.path(a0, "tables", "sample_summary.csv")); g <- utils::read.csv(file.path(a0, "tables", "gene_summary.csv"))
v <- utils::read.csv(file.path(a0, "tables", "variants.csv")); silent <- utils::read.csv(file.path(a0, "tables", "silent_variants.csv"))
check(nrow(s) == 193 && nrow(g) == 1241, "PRINTED locked maftools vignette: 193 samples,1241 genes")
check(nrow(v) == 1732 && nrow(silent) == 475, "PRINTED locked vignette:1732 non-silent,475 silent")
tmb <- utils::read.csv(file.path(a0, "tables", "tmb.csv")); ints <- utils::read.csv(file.path(a0, "tables", "interactions.csv"))
check(nrow(tmb) == 192 && nrow(ints) == choose(25, 2) && "pAdj" %in% names(ints), "native TMB192 (package omits zero non-silent sample) and all interaction pairs/pAdj")
j <- utils::read.csv(file.path(a0, "tables", "clinical_join.csv")); check(nrow(j) == 200 && sum(!j$matched) == 7, "clinical-only seven rows are reported")
figspec <- jsonlite::fromJSON(file.path(a0, "figures", "oncoplot.figure_spec.json"), simplifyVector = FALSE)
check(grepl("193 samples", figspec$caption), "oncoplot observed-sample denominator 193 (factor IDs preserved)")
a1 <- file.path(tmp, "from-run"); z <- run(base, "--from-run", shQuote(a0), "--outdir", shQuote(a1)); check(z$status == 0 && sha(file.path(a0, "tables", "gene_summary.csv")) == sha(file.path(a1, "tables", "gene_summary.csv")), "native MAF from-run equal")
check(read_handoff(a1)$ecosystem == "neutral", "neutral ecosystem handoff")
a2 <- file.path(tmp, "spec"); check(run("--spec", shQuote(file.path(a0, "provenance", "resolved_spec.json")), "--outdir", shQuote(a2))$status == 0 && sha(file.path(a0, "tables", "gene_summary.csv")) == sha(file.path(a2, "tables", "gene_summary.csv")), "resolved spec replay")
for (tool in c("check_calls.R", "lint_r.py", "check_flag_docs.py")) {
 cmd <- if (endsWith(tool, ".R")) "Rscript" else "python3"
 check(system2(cmd, c(shQuote(file.path(suite, "tools", tool)), shQuote(mod))) == 0, tool)
}
gold <- c("tables/gene_summary.csv", "tables/sample_summary.csv", "tables/tmb.csv", "tables/interactions.csv")
if (nzchar(Sys.getenv("OMICSTAT_WRITE_GOLDEN"))) os_golden_write(mod, a0, gold)
gc <- os_golden_check(mod, a0); check(gc$status == "PASS", paste("container golden", gc$reason))
cat("SMOKE PASSED:", n, "checks\n")

# Local region subset: same native interval input, TMB parity, full variants retained.
regions <- file.path(tmp,"regions.tsv")
write.table(data.frame(chrom="1",start=0,end=250000000),regions,sep="\t",row.names=FALSE,quote=FALSE)
ro <- file.path(tmp,"regions")
z <- run("--call-source","TCGA-LAML-vignette","--input",shQuote(maf),"--clinical",shQuote(clin),"--capture-regions",shQuote(regions),"--capture-regions-source","user-derived-chr1-GRCh37","--outdir",shQuote(ro))
check(z$status==0,paste("captureRegions CLI",paste(tail(z$out,2),collapse=" | ")))
m <- readRDS(file.path(a0,"objects/maf.rds"))
sink <- tempfile(fileext=".pdf");pdf(sink)
nt <- as.data.frame(maftools::tmb(m,captureRegions=regions,verbose=FALSE));dev.off();unlink(sink)
got <- read.csv(file.path(ro,"tables/tmb.csv"))
native_csv <- tempfile(fileext=".csv");write.csv(nt,native_csv,row.names=FALSE)
check(identical(got,read.csv(native_csv)),"native captureRegions TMB parity")
check(!identical(got,tmb),"region subset changes native TMB")
check(sha(file.path(ro,"tables/variants.csv"))==sha(file.path(a0,"tables/variants.csv")),"full variants retained")
pv <- jsonlite::read_json(file.path(ro,"provenance/provenance.json"))
check(pv$capture$sha256==sha(regions)&&pv$capture$source=="user-derived-chr1-GRCh37","region source/hash provenance")
check(any(grepl(sha(regions),readLines(file.path(ro,"draft/methods_results.md")),fixed=TRUE)),"region hash Methods")
z <- run(base,"--input",shQuote(maf),"--capture-regions",shQuote(regions),"--outdir",shQuote(file.path(tmp,"conflicting")))
check(z$status!=0,"mutually exclusive territory inputs")
z <- run("--call-source","TCGA-LAML-vignette","--input",shQuote(maf),"--outdir",shQuote(file.path(tmp,"missing-territory")))
check(z$status!=0&&any(grepl("OS_MISSING_PARAMETER",z$out)),"required territory input")
