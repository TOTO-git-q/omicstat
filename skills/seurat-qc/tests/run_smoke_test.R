# requires: Seurat SeuratObject Matrix jsonlite digest ggplot2 patchwork
script <- normalizePath(sub("^--file=","",grep("^--file=",commandArgs(FALSE),value=TRUE)[1])); root <- normalizePath(file.path(dirname(script),"..","..","..")); mod <- file.path(root,"skills","seurat-qc")
for(f in c("module_kit.R","handoff.R","calls_check.R")) source(file.path(root,"skills","_shared","scripts",f))
scratch <- Sys.getenv("OMICSTAT_TEST_TMP", tempdir())
dir.create(scratch, recursive=TRUE, showWarnings=FALSE)
checks <- 0L
check <- function(ok,label) { if(!isTRUE(ok)) stop(paste("FAIL",label)); checks <<- checks+1L; cat("PASS",label,"\n") }
run <- function(argv,ok=TRUE,code=NULL) {
 pos <- which(startsWith(argv,"--")); dup <- pos[duplicated(argv[pos],fromLast=TRUE)]; if(length(dup)) argv <- argv[-sort(unique(c(dup,dup+1L)))]
 log <- tempfile(tmpdir=scratch)
 status <- system2("Rscript",c(file.path(mod,"scripts","run_seurat_qc.R"),shQuote(argv)),stdout=log,stderr=log)
 txt <- paste(readLines(log,warn=FALSE),collapse="\n")
 if(ok && status!=0L) stop(txt)
 if(!ok) check(status!=0L && grepl(code,txt,fixed=TRUE),paste("typed",code))
 txt
}
for(tool in c("check_defaults.py","check_flag_docs.py","lint_r.py")) check(system2("python3",c(file.path(root,"tools",tool),mod))==0L,tool)
cc <- check_calls(list.files(file.path(mod,"scripts"),pattern="[.]R$",full.names=TRUE),file.path(mod,"scripts","calls_registry.json")); check(cc$ok,paste(cc$problems,collapse=";"))
dd <- check_default_drift(file.path(mod,"scripts","calls_registry.json")); check(dd$ok,paste(dd$problems,collapse=";"))
archive <- file.path(root,"acceptance","data","pbmc3k_filtered_gene_bc_matrices.tar.gz")
if(!file.exists(archive)) { cat("SKIP missing PBMC anchor\n"); quit(status=0) }
check(digest::digest(file=archive,algo="sha256")=="847d6ebd9a1ec9a768f2be7e40ca42cbfe75ebeb6d76a4c24167041699dc28b5","anchor SHA256")
raw <- file.path(scratch,"pbmc3k"); dir.create(raw,showWarnings=FALSE)
utils::untar(archive,exdir=raw)
data <- file.path(raw,"filtered_gene_bc_matrices","hg19")
base <- c("--input",data,"--input-format","10x","--organism","Homo_sapiens","--feature-type","symbol","--mito-pattern","^MT-","--min-cells","3","--create-min-features","200","--min-features","200","--max-features","2500","--min-counts","0","--max-counts","1000000000","--max-mito","5")
out <- file.path(scratch,"qc_anchor"); run(c(base,"--outdir",out))
d <- read.csv(file.path(out,"tables","cell_qc.csv")); flow <- read.csv(file.path(out,"tables","filter_flow.csv"))
check(nrow(d)==2700L,"PRINTED tutorial 2700 cells")
check(d$nCount_RNA[1]==2419 && d$nFeature_RNA[1]==779 && abs(d$percent.mt[1]-3.0177759)<5e-8,"PRINTED tutorial first cell")
x <- Seurat::Read10X(data); ref <- SeuratObject::CreateSeuratObject(x,project="pbmc3k",min.cells=3,min.features=200)
check(nrow(ref)==13714L,"PRINTED tutorial 13714 genes after creation")
ref$percent.mt <- Seurat::PercentageFeatureSet(ref,pattern="^MT-")
ref <- subset(ref,subset=nFeature_RNA>200 & nFeature_RNA<2500 & percent.mt<5)
y <- readRDS(file.path(out,"objects","seurat.rds"))
check(identical(colnames(y),colnames(ref)) && nrow(y)==nrow(ref),"REPLAY tutorial strict QC cell and feature identities")
check(flow$retained==ncol(y) && flow$after_creation==2700L,"flow reconciles")
replay <- file.path(scratch,"qc_replay"); run(c("--spec",file.path(out,"provenance","resolved_spec.json"),"--outdir",replay))
paths <- c("tables/cell_qc.csv","tables/filter_flow.csv","figures/qc_metrics.png","figures/qc_scatter_percent.mt.png","figures/qc_scatter_nFeature_RNA.png")
sha <- function(dir,p) digest::digest(file=file.path(dir,p),algo="sha256")
check(all(vapply(paths,function(p) identical(sha(out,p),sha(replay,p)),TRUE)),"determinism tables and PNG")
alt <- file.path(scratch,"qc_alt"); run(c(base,"--max-mito","10","--outdir",alt))
check(ncol(readRDS(file.path(alt,"objects","seurat.rds")))>ncol(y),"mito flag effectiveness")
run(c(base,"--min-features","999999","--max-features","1000000","--outdir",file.path(scratch,"qc_none")),FALSE,"OS_QC_BLOCKER")
run(c(base,"--mito-pattern","NOT_A_GENE","--outdir",file.path(scratch,"qc_mito")),FALSE,"OS_MITO_FEATURES")
mat <- matrix(c(1,0.5,2,3),2,dimnames=list(c("MT-A","B"),c("a","b"))); saveRDS(mat,file.path(scratch,"invalid.rds"))
run(c(base,"--input",file.path(scratch,"invalid.rds"),"--input-format","rds","--outdir",file.path(scratch,"qc_invalid")),FALSE,"OS_INVALID_COUNTS")
h <- read_handoff(out,expect=list(seurat="Seurat"),front_end_ecosystem="seurat"); check(isTRUE(h$state$seurat$qc_done) && !isTRUE(h$state$seurat$normalized),"chain QC state")
if(Sys.getenv("OMICSTAT_WRITE_GOLDEN")=="1") os_golden_write(mod,out,paths)
g <- os_golden_check(mod,out); check(g$status=="PASS",paste("goldens",g$status,paste(g$problems,collapse=",")))
check(!file.exists(file.path(root,"Rplots.pdf")),"no Rplots.pdf")
cat(checks,"checks PASS\n")
